use crate::command::{build_args, normalize_robocopy_path, quote_windows_arg};
use crate::model::RobocopyJob;
use crate::parser::{apply_switch, tokenize_windows_cmdline};
use anyhow::{Result, bail};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum RcjSection {
    None,
    If,
    Xf,
    Xd,
}

/// Decodes UTF-8 or UTF-16LE/BE Robocopy `.rcj` job bytes into a UTF-8 `String`.
pub fn decode_rcj_bytes(bytes: &[u8]) -> Result<String> {
    if bytes.starts_with(&[0xFF, 0xFE]) {
        let mut units = Vec::with_capacity((bytes.len() - 2) / 2);
        for chunk in bytes[2..].as_chunks::<2>().0 {
            units.push(u16::from_le_bytes(*chunk));
        }
        return Ok(String::from_utf16(&units)?);
    }
    if bytes.starts_with(&[0xFE, 0xFF]) {
        let mut units = Vec::with_capacity((bytes.len() - 2) / 2);
        for chunk in bytes[2..].as_chunks::<2>().0 {
            units.push(u16::from_be_bytes(*chunk));
        }
        return Ok(String::from_utf16(&units)?);
    }
    if bytes.starts_with(&[0xEF, 0xBB, 0xBF]) {
        return Ok(String::from_utf8(bytes[3..].to_vec())?);
    }
    match std::str::from_utf8(bytes) {
        Ok(s) => Ok(s.to_string()),
        Err(_) => bail!("Unrecognized character encoding in .rcj file (expected UTF-8 or UTF-16)"),
    }
}

/// Strips inline `:: ...` comments and surrounding quotes from a single `.rcj` entry.
fn clean_rcj_line(raw: &str) -> String {
    let mut in_quotes = false;
    let chars: Vec<char> = raw.chars().collect();
    let mut cut = chars.len();
    let mut i = 0;
    while i < chars.len() {
        if chars[i] == '"' {
            in_quotes = !in_quotes;
        } else if !in_quotes && chars[i] == ':' && i + 1 < chars.len() && chars[i + 1] == ':' {
            cut = i;
            break;
        }
        i += 1;
    }
    let prefix: String = chars[..cut].iter().collect();
    prefix.trim().to_string()
}

fn unquote_rcj_value(s: &str) -> String {
    let t = s.trim();
    if t.len() >= 2 && t.starts_with('"') && t.ends_with('"') {
        let mut tokens = tokenize_windows_cmdline(t);
        if tokens.len() == 1 {
            return tokens.remove(0);
        }
    }
    t.to_string()
}

/// Parses a Microsoft Robocopy `.rcj` job file (UTF-8 or UTF-16LE/BE) into a `RobocopyJob`.
pub fn parse_rcj(bytes: &[u8]) -> Result<(RobocopyJob, Vec<String>)> {
    let text = decode_rcj_bytes(bytes)?;
    let mut job = RobocopyJob::empty_cli_defaults();
    let mut warnings = Vec::new();
    let mut section = RcjSection::None;

    for raw_line in text.lines() {
        let cleaned = clean_rcj_line(raw_line);
        if cleaned.is_empty() {
            continue;
        }

        let upper = cleaned.to_ascii_uppercase();
        if upper == "/IF" {
            section = RcjSection::If;
            continue;
        }
        if upper == "/XF" {
            section = RcjSection::Xf;
            continue;
        }
        if upper == "/XD" {
            section = RcjSection::Xd;
            continue;
        }

        if upper.starts_with("/SD:") {
            section = RcjSection::None;
            job.source = unquote_rcj_value(&cleaned[4..]);
            continue;
        }
        if upper.starts_with("/DD:") {
            section = RcjSection::None;
            job.destination = unquote_rcj_value(&cleaned[4..]);
            continue;
        }

        if cleaned.starts_with('/') {
            section = RcjSection::None;
            apply_switch(&cleaned, &mut job, &mut warnings);
            continue;
        }

        match section {
            RcjSection::If => {
                for tok in tokenize_windows_cmdline(&cleaned) {
                    if !tok.trim().is_empty() {
                        job.file_specs.push(tok);
                    }
                }
            }
            RcjSection::Xf => {
                for tok in tokenize_windows_cmdline(&cleaned) {
                    if !tok.trim().is_empty() {
                        job.selection.exclude_files.push(tok);
                    }
                }
            }
            RcjSection::Xd => {
                for tok in tokenize_windows_cmdline(&cleaned) {
                    if !tok.trim().is_empty() {
                        job.selection.exclude_dirs.push(tok);
                    }
                }
            }
            RcjSection::None => {
                warnings.push(format!("Unexpected .rcj token outside section: '{cleaned}'"));
            }
        }
    }

    Ok((job, warnings))
}

/// Serializes a `RobocopyJob` into a standard Microsoft Robocopy `.rcj` job file.
pub fn serialize_rcj(job: &RobocopyJob) -> String {
    let mut lines = Vec::new();
    lines.push("::".to_string());
    lines.push(format!(":: Robocopy Job File - {}", job.name));
    lines.push(":: Generated by robocopy2rust".to_string());
    lines.push("::".to_string());
    lines.push(String::new());

    if !job.job_files.no_source_dir && !job.source.trim().is_empty() {
        lines.push(format!(
            "/SD:{}",
            quote_windows_arg(&normalize_robocopy_path(&job.source))
        ));
    } else if job.job_files.no_source_dir {
        lines.push("/NOSD".to_string());
    }

    if !job.job_files.no_dest_dir && !job.destination.trim().is_empty() {
        lines.push(format!(
            "/DD:{}",
            quote_windows_arg(&normalize_robocopy_path(&job.destination))
        ));
    } else if job.job_files.no_dest_dir {
        lines.push("/NODD".to_string());
    }

    let specs: Vec<&str> = job
        .file_specs
        .iter()
        .map(String::as_str)
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .collect();
    if !specs.is_empty() {
        lines.push(String::new());
        lines.push("/IF :: Include Files".to_string());
        for s in specs {
            lines.push(format!("\t{}", quote_windows_arg(s)));
        }
    }

    // Re-use build_args while filtering out positional source/dest/file_specs and /XF /XD sections
    let mut clone = job.clone();
    clone.source.clear();
    clone.destination.clear();
    clone.file_specs.clear();
    clone.selection.exclude_files.clear();
    clone.selection.exclude_dirs.clear();
    clone.job_files.no_source_dir = false;
    clone.job_files.no_dest_dir = false;

    let switch_args = build_args(&clone);
    if !switch_args.is_empty() {
        lines.push(String::new());
        lines.push(":: Switches".to_string());
        for arg in switch_args {
            lines.push(arg);
        }
    }

    let xf: Vec<&str> = job
        .selection
        .exclude_files
        .iter()
        .map(String::as_str)
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .collect();
    if !xf.is_empty() {
        lines.push(String::new());
        lines.push("/XF :: Exclude Files".to_string());
        for item in xf {
            lines.push(format!("\t{}", quote_windows_arg(item)));
        }
    }

    let xd: Vec<&str> = job
        .selection
        .exclude_dirs
        .iter()
        .map(String::as_str)
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .collect();
    if !xd.is_empty() {
        lines.push(String::new());
        lines.push("/XD :: Exclude Directories".to_string());
        for item in xd {
            lines.push(format!("\t{}", quote_windows_arg(&normalize_robocopy_path(item))));
        }
    }

    lines.push(String::new());
    lines.join("\r\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rcj_roundtrip_utf8_and_utf16le() {
        let mut job = RobocopyJob::empty_cli_defaults();
        job.name = "Daily Sync".to_string();
        job.source = r"C:\Work\Src".to_string();
        job.destination = r"E:\Backup\Work".to_string();
        job.file_specs = vec!["*.rs".to_string(), "*.toml".to_string()];
        job.copy.subdirectories_including_empty = true;
        job.copy.multithreaded = Some(12);
        job.retry.retries = Some(3);
        job.retry.wait_seconds = Some(5);
        job.selection.exclude_files = vec!["*.pdb".to_string()];
        job.selection.exclude_dirs = vec!["target".to_string()];

        let rcj_text = serialize_rcj(&job);
        let (parsed_utf8, warnings) = parse_rcj(rcj_text.as_bytes()).unwrap();
        assert!(warnings.is_empty(), "warnings: {warnings:?}");
        assert_eq!(parsed_utf8.source, job.source);
        assert_eq!(parsed_utf8.destination, job.destination);
        assert_eq!(parsed_utf8.file_specs, job.file_specs);
        assert_eq!(parsed_utf8.copy.multithreaded, Some(12));
        assert_eq!(parsed_utf8.selection.exclude_files, job.selection.exclude_files);
        assert_eq!(parsed_utf8.selection.exclude_dirs, job.selection.exclude_dirs);

        // Encode as UTF-16LE with BOM (Robocopy /SAVE default on Windows)
        let mut utf16 = vec![0xFFu8, 0xFEu8];
        for unit in rcj_text.encode_utf16() {
            utf16.extend_from_slice(&unit.to_le_bytes());
        }
        let (parsed_u16, warnings_u16) = parse_rcj(&utf16).unwrap();
        assert!(warnings_u16.is_empty());
        assert_eq!(parsed_u16.source, job.source);
        assert_eq!(parsed_u16.destination, job.destination);
    }

    #[test]
    fn rcj_roundtrip_drive_root_and_multi_token_lines() {
        let mut job = RobocopyJob::empty_cli_defaults();
        job.source = r"C:\".to_string();
        job.destination = r"D:\My Backup\".to_string();
        job.file_specs = vec!["*.docx".to_string(), "notes 2026.txt".to_string()];

        let rcj_text = serialize_rcj(&job);
        let (parsed, warnings) = parse_rcj(rcj_text.as_bytes()).unwrap();
        assert!(warnings.is_empty(), "warnings: {warnings:?}");
        assert_eq!(parsed.source, r"C:\");
        assert_eq!(parsed.destination, r"D:\My Backup");
        assert_eq!(parsed.file_specs, job.file_specs);

        let multi = "/SD:\"C:\\\\\"\r\n/DD:\"D:\\My Backup\"\r\n/IF\r\n\t*.tmp \"two words.txt\"\r\n";
        let (multi_parsed, multi_warnings) = parse_rcj(multi.as_bytes()).unwrap();
        assert!(multi_warnings.is_empty(), "warnings: {multi_warnings:?}");
        assert_eq!(multi_parsed.source, r"C:\");
        assert_eq!(multi_parsed.file_specs, vec!["*.tmp", "two words.txt"]);
    }
}
